// ── 6. dmHash11 TS ───────────────────────────────────────
const legacyDmHash11 = (n) => {
  const fract = (v) => v - Math.floor(v);
  let x = fract(n * 0.1031);
  let y = fract(n * 0.1030);
  let z = fract(n * 0.0973);
  const d = x * (y + 33.33) + y * (x + 33.33) + z * (z + 33.33);
  x += d; y += d; z += d;
  return fract((x + y) * z);
};
{
  let ok = true;
  for (let i = -512; i <= 512; i++) {
    const n = i * 0.731 + 17.17;
    if (dmHash11(n) !== legacyDmHash11(n)) { ok = false; break; }
  }
  for (const n of [0, 1, -1, 33.33, 127.1, 1e6, -98765.4321]) {
    if (dmHash11(n) !== legacyDmHash11(n)) ok = false;
  }
  check('6 shared dmHash11 matches the legacy scene body over the grid', ok);
}
