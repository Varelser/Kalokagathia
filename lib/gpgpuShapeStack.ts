export type ShapeStackSourceKind = 'emit' | 'shape' | 'path' | 'text';

/**
 * One source description, in the fat-interface style of the
 * operator layers: every family's parameters live on the one
 * interface and only the fields of the named `kind` are read.
 */
export interface ShapeStackSourceSpec {
  kind: ShapeStackSourceKind;
  /** emit: the E1 shape law's shape. */
  shape: GpgpuEmitShape;
  /** emit: the emitter radius the law samples over. 0 =
   *  resolve from the supply radius, then 1. */
  radius: number;
  /** emit: the light position ('light' shape only). */
  lightPos: { x: number; y: number; z: number } | null;
  /** shape: the morph target kind. */
  target: GpgpuMorphTargetKind;
  /** shape: the morph builder's world-units multiplier. */
  worldScale: number;
  /** shape: the morph builder's normalised-space jitter. */
  jitter: number;
  /** path: the SVG document text. */
  svg: string;
  /** path: how the arc parameter walks the subpaths. */
  subpathMode: MorphPathSubpathMode;
  /** text: the string to lay out. */
  text: string;
  /** text: glyph flattening tolerance; 0 = the text
   *  pipeline's own default. */
  flatness: number;
}

/** The authored stack: one source plus the two columns. */
export interface ShapeStackSpec {
  source: ShapeStackSourceSpec;
  /** Deform column (WP8 phase A grammar), resolved. */
  deform: DeformOp[];
  /** Distribution column (stage 2 B5 grammar), resolved. */
  distribution: DistOp[];
  /** Distribution radius override; 0 = auto (the supply
   *  radius, then the emit source's radius, then 1). */
  distributionRadius: number;
}

/**
 * What the caller supplies at resolve time. Nothing here is
 * authored or serialised: the count and seed fix the point
 * set, and the font is the text pipeline's session material.
 */
export interface ShapeStackSupply {
  /** Number of points to resolve (integer >= 1). */
  count: number;
  /** Seed for the stochastic sources (emit; the morph
   *  builder's own seed). Default 0. */
  seed?: number;
  /** Distribution radius override, and the emit radius
   *  fallback when the source authors none. */
  radius?: number;
  /** Session font for the text source (lib/textExtrude.ts
   *  holds it the same way); null / absent = a text source
   *  cannot resolve. */
  font?: Font | null;
}

/** The resolved point set, in the bake lanes' conventions. */
export interface ShapeStackPoints {
  count: number;
  /** Flat xyz triples, count * 3. */
  positions: Float32Array;
  /** Flat xyz triples, count * 3 — only the shape source
   *  supplies normals; null for every other source. */
  normals: Float32Array | null;
  /** Per-point alpha, count wide — only the shape source
   *  supplies it (the morph builder's w lane); null else. */
  alpha: Float32Array | null;
}

const SOURCE_KINDS: ReadonlySet<string> = new Set(['emit', 'shape', 'path', 'text']);
const SUBPATH_MODES: ReadonlySet<string> = new Set(['proportional', 'even', 'first']);

function finiteOr(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

function positiveOr(value: unknown, fallback: number): number {
  const v = finiteOr(value, NaN);
  return v > 0 ? v : fallback;
}

function baseSource(kind: ShapeStackSourceKind): ShapeStackSourceSpec {
  return {
    kind,
    shape: 'sphere',
    radius: 0,
    lightPos: null,
    target: 'shell',
    worldScale: 1,
    jitter: 0,
    svg: '',
    subpathMode: 'proportional',
    text: '',
    flatness: 0,
  };
}

/**
 * The operator columns accept either authored form: the
 * list itself (the single-description form) or the JSON
 * string the config keys carry. Both go through the
 * existing parsers verbatim, so the sanitisation is the
 * bakes' own.
 */
function parseColumn(raw: unknown, parse: (raw: string | null | undefined) => unknown): unknown {
  if (typeof raw === 'string') return parse(raw);
  if (Array.isArray(raw)) return parse(JSON.stringify(raw));
  return parse(undefined);
}

/**
 * Parse and sanitise the authored JSON description. Returns
 * null when the description names no generatable source:
 * non-JSON, non-object, a missing / unknown source kind, an
 * unknown morph target, a path source with no SVG text, or
 * a text source with no string. The columns resolve toward
 * identity exactly as their own grammars do.
 */
export function parseShapeStack(raw: string | null | undefined): ShapeStackSpec | null {
  if (!raw) return null;
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!parsed || typeof parsed !== 'object') return null;
  const root = parsed as Record<string, unknown>;
  const srcRaw = root.source;
  if (!srcRaw || typeof srcRaw !== 'object') return null;
  const s = srcRaw as Record<string, unknown>;
  const kind = s.kind;
  if (typeof kind !== 'string' || !SOURCE_KINDS.has(kind)) return null;
  const source = baseSource(kind as ShapeStackSourceKind);
  if (kind === 'emit') {
    const shape = s.shape;
    if (typeof shape === 'string' && Object.prototype.hasOwnProperty.call(EMIT_SHAPE_IDS, shape)) {
      source.shape = shape as GpgpuEmitShape;
    }
    source.radius = positiveOr(s.radius, 0);
    const lp = s.lightPos;
    if (lp && typeof lp === 'object') {
      const l = lp as Record<string, unknown>;
      const x = finiteOr(l.x, NaN);
      const y = finiteOr(l.y, NaN);
      const z = finiteOr(l.z, NaN);
      if (Number.isFinite(x) && Number.isFinite(y) && Number.isFinite(z)) {
        source.lightPos = { x, y, z };
      }
    }
  } else if (kind === 'shape') {
    const target = s.target;
    if (
      typeof target !== 'string' ||
      !(GPGPU_MORPH_TARGETS as readonly string[]).includes(target)
    ) {
      return null;
    }
    source.target = target as GpgpuMorphTargetKind;
    source.worldScale = positiveOr(s.worldScale, 1);
    source.jitter = Math.max(0, finiteOr(s.jitter, 0));
  } else if (kind === 'path') {
    if (typeof s.svg !== 'string' || s.svg.length === 0) return null;
    source.svg = s.svg;
    const mode = s.subpathMode;
    if (typeof mode === 'string' && SUBPATH_MODES.has(mode)) {
      source.subpathMode = mode as MorphPathSubpathMode;
    }
  } else {
    // text
    if (typeof s.text !== 'string' || s.text.length === 0) return null;
    source.text = s.text;
    source.flatness = positiveOr(s.flatness, 0);
  }
  return {
    source,
    deform: parseColumn(root.deform, parseDeformOps) as DeformOp[],
    distribution: parseColumn(root.distribution, parseDistributionOps) as DistOp[],
    distributionRadius: positiveOr(root.distributionRadius, 0),
  };
}

// ---------------------------------------------------------------------------
// Source generators (each calls the existing generator directly)
// ---------------------------------------------------------------------------

/**
 * Emit source: the E1 shape law sampled from the seeded
 * RNG, one point after another in the law's own draw
 * order — the same loop a direct caller of sampleEmitShape
 * writes, so the two agree point for point.
 */
export function generateEmitSourcePoints(
  shape: GpgpuEmitShape,
  count: number,
  seed: number,
  radius: number,
  lightPos?: { x: number; y: number; z: number } | null,
): Float32Array {
  const next = createSeededRng(seed);
  const out = new Float32Array(count * 3);
  for (let i = 0; i < count; i++) {
    const p = sampleEmitShape(shape, next, radius, lightPos ?? null);
    out[i * 3] = p[0];
    out[i * 3 + 1] = p[1];
    out[i * 3 + 2] = p[2];
  }
  return out;
}

/**
 * Shape source: the morph builder at the smallest texSize
 * whose square covers `count`. The builder's lanes are
 * sliced to the first `count` texels: positions and alpha
 * from `data`, normals from `normalData` (the builder's own
 * contract — zero normals for most targets, radial for the
 * obj shell fallback).
 */
export function generateShapeSourcePoints(
  target: GpgpuMorphTargetKind,
  count: number,
  seed: number,
  worldScale: number,
  jitter: number,
): ShapeStackPoints | null {
  if (!Number.isInteger(count) || count < 1) return null;
  const texSize = Math.max(1, Math.ceil(Math.sqrt(count)));
  const built = buildGpgpuMorphTargetDataWithNormals({
    texSize,
    target,
    worldScale,
    jitter,
    seed,
  });
  const positions = new Float32Array(count * 3);
  const normals = new Float32Array(count * 3);
  const alpha = new Float32Array(count);
  for (let i = 0; i < count; i++) {
    positions[i * 3] = built.data[i * 4];
    positions[i * 3 + 1] = built.data[i * 4 + 1];
    positions[i * 3 + 2] = built.data[i * 4 + 2];
    alpha[i] = built.data[i * 4 + 3];
    normals[i * 3] = built.normalData[i * 4];
    normals[i * 3 + 1] = built.normalData[i * 4 + 1];
    normals[i * 3 + 2] = built.normalData[i * 4 + 2];
  }
  return { count, positions, normals, alpha };
}

/**
 * Path source: equidistant arc parameters (i + 0.5) / count
 * resolved through lib/pathGeometry.ts, z = 0.
 */
export function generatePathSourcePoints(
  geom: PathGeometry,
  count: number,
  subpathMode: MorphPathSubpathMode,
): Float32Array {
  const out = new Float32Array(count * 3);
  for (let i = 0; i < count; i++) {
    const p = resolvePathPoint(geom, (i + 0.5) / count, subpathMode);
    out[i * 3] = p.x;
    out[i * 3 + 1] = p.y;
    out[i * 3 + 2] = 0;
  }
  return out;
}

/**
 * Contour source (the text family's point walk): the
 * contours are treated as closed loops, concatenated in
 * order, and walked by arc length at the equidistant
 * parameters (i + 0.5) / count of the total length, z = 0.
 * Returns null when the contours carry no length at all.
 */
export function generateContourSourcePoints(
  contours: readonly VectorContour[],
  count: number,
): Float32Array | null {
  // Flatten the loops into one segment list once: each
  // segment carries its start point, delta and length.
  const segX: number[] = [];
  const segY: number[] = [];
  const segDx: number[] = [];
  const segDy: number[] = [];
  const segLen: number[] = [];
  let total = 0;
  for (const contour of contours) {
    const n = contour.length;
    if (n < 2) continue;
    for (let k = 0; k < n; k++) {
      const a = contour[k];
      const b = contour[(k + 1) % n];
      const dx = b[0] - a[0];
      const dy = b[1] - a[1];
      const len = Math.sqrt(dx * dx + dy * dy);
      if (!(len > 0)) continue;
      segX.push(a[0]);
      segY.push(a[1]);
      segDx.push(dx);
      segDy.push(dy);
      segLen.push(len);
      total += len;
    }
  }
  if (!(total > 0) || segLen.length === 0) return null;
  const out = new Float32Array(count * 3);
  let seg = 0;
  let segStart = 0; // arc length at the current segment's start
  for (let i = 0; i < count; i++) {
    const target = ((i + 0.5) / count) * total;
    while (seg < segLen.length - 1 && segStart + segLen[seg] < target) {
      segStart += segLen[seg];
      seg += 1;
    }
    const t = (target - segStart) / segLen[seg];
    out[i * 3] = segX[seg] + segDx[seg] * t;
    out[i * 3 + 1] = segY[seg] + segDy[seg] * t;
    out[i * 3 + 2] = 0;
  }
  return out;
}

