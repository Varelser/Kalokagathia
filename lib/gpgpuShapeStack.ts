// Shape stack (Layer 1 WP8, phase B).
//
// Design: the single resolution point for the stacking
// grammar "source -> deform column -> distribution column".
// Until this module, every shape source lived behind its own
// keys and its own module — the emitter shape law
// (lib/gpgpuEmitShapes.ts), the morph targets' parametric
// shapes and media sources (lib/gpgpuMorphTargets.ts), the
// authored paths (lib/pathGeometry.ts), the text contours
// (lib/textExtrude.ts) — and the two operator columns that
// already exist as general grammar, the deform stack
// (lib/gpgpuDeformStack.ts, WP8 phase A) and the distribution
// layer (lib/gpgpuDistribution.ts, stage 2 B5), each had to
// be wired into each consumer separately. This module is the
// one authored description that names a source and the two
// columns, and the one pure resolver that runs them in the
// fixed order:
//
//   source points -> deform ops (list order)
//                 -> distribution ops (list order)
//
// The resolver changes no existing module: each source is
// generated by calling the existing generator directly (the
// emit law's seeded sampler, the morph builder, the path
// resolver, the text layout), and the columns are the
// existing parsers / appliers, so a stack whose columns are
// empty resolves to exactly the points the source's own
// generator produces — the identity the tests pin per source
// family. The result is shaped for the existing bake inputs:
// `positions` is a flat xyz triple list (the convention of
// the morph bake's objPoints / dataPoints lanes), and
// shapeStackToCloudRgba packs it into the morph-layout RGBA
// cloud that lib/gpgpuInitialData.ts consumes as its `cloud`
// emission source.
//
// Sources (authored as {kind, ...params}):
//   emit  {shape, radius, lightPos}
//         the E1 emitter shape law, sampled from the seeded
//         RNG (lib/seededRng.ts) in the law's own draw order.
//   shape {target, worldScale, jitter}
//         a parametric morph target, built by
//         buildGpgpuMorphTargetDataWithNormals at the
//         smallest texSize whose square covers the count;
//         the first `count` texels are the source points.
//         This is the one source that also supplies normals
//         and per-point alpha (the builder's own lanes).
//   path  {svg, subpathMode}
//         an SVG document read as path geometry; points are
//         placed at equidistant arc parameters
//         (i + 0.5) / count over the geometry, z = 0, in the
//         path pipeline's normalised morph space.
//   text  {text, flatness}
//         a string laid out by lib/textExtrude.ts into
//         classified contours; points walk the concatenated
//         contours by arc length at the same equidistant
//         parameters, z = 0. The font is NEVER authored —
//         like every text-extrude consumer, the resolver
//         reads the session font from the supply, so a stack
//         naming text resolves only while the caller supplies
//         the font the string was set in.
//
// CSG is deliberately NOT a source here. The CSG pipeline
// (lib/csg.ts) runs through a Web Worker hosting the
// manifold-3d WASM build: generation is asynchronous and
// queued, and its cost is a solid build plus a surface
// sampling per resolve — neither fits this layer's contract
// (synchronous pure functions of the authored description,
// cheap enough to resolve per bake). A CSG source would
// need the caller to pre-build and pre-sample the solid and
// hand the points in as a cloud, which the existing bake
// lanes already accept without this module.
//
// Identity / tolerance discipline, in the operator layers'
// style: parsing is tolerant — an unusable description
// (non-JSON, non-object, unknown source kind, a source whose
// own parameters name nothing generatable) resolves to null
// rather than substituting a different shape silently; the
// deform / distribution columns reuse the existing parsers
// verbatim, so their sanitisation cannot drift from the
// bakes'. A stack with both columns empty is the identity
// over its source. The columns consume no RNG draws; the
// emit source consumes exactly the draws its own law
// consumes per point, in order.
//
// Normals / alpha: only the shape source supplies them.
// The columns move positions only, so supplied normals pass
// through unchanged — the same documented approximation the
// morph bake's form grammar makes (it deforms points and
// leaves normals as-is).

