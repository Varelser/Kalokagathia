// Resolution
// ---------------------------------------------------------------------------

function resolveDistributionRadius(spec: ShapeStackSpec, supply: ShapeStackSupply): number {
  if (supply.radius !== undefined && supply.radius > 0) return supply.radius;
  if (spec.distributionRadius > 0) return spec.distributionRadius;
  if (spec.source.kind === 'emit' && spec.source.radius > 0) return spec.source.radius;
  return 1;
}

/**
 * Resolve a parsed stack to its point set: generate the
 * source points, apply the deform column in list order,
 * then the distribution column in list order. Returns null
 * when the source cannot generate under this supply (a
 * text source with no font or an unlayable string, a path
 * source whose SVG carries no geometry, an unusable
 * count). With both columns empty the result is the source
 * generator's own output, bit for bit.
 */
export function resolveShapeStackPoints(
  spec: ShapeStackSpec,
  supply: ShapeStackSupply,
): ShapeStackPoints | null {
  const count = supply.count;
  if (!Number.isInteger(count) || count < 1) return null;
  const seed = supply.seed ?? 0;
  const src = spec.source;
  let base: ShapeStackPoints | null = null;
  if (src.kind === 'emit') {
    const radius = src.radius > 0 ? src.radius : supply.radius !== undefined && supply.radius > 0 ? supply.radius : 1;
    base = {
      count,
      positions: generateEmitSourcePoints(src.shape, count, seed, radius, src.lightPos),
      normals: null,
      alpha: null,
    };
  } else if (src.kind === 'shape') {
    base = generateShapeSourcePoints(src.target, count, seed, src.worldScale, src.jitter);
  } else if (src.kind === 'path') {
    const geom = parseSvgPathGeometry(src.svg);
    if (!geom) return null;
    base = {
      count,
      positions: generatePathSourcePoints(geom, count, src.subpathMode),
      normals: null,
      alpha: null,
    };
  } else {
    // text: the font comes from the supply (session
    // material, never authored); without it the source
    // cannot resolve.
    const font = supply.font ?? null;
    if (!font) return null;
    const laid = layoutTextExtrudeContours(font, src.text, src.flatness > 0 ? src.flatness : undefined);
    if (!laid.ok) return null;
    const positions = generateContourSourcePoints(laid.layout.contours, count);
    if (!positions) return null;
    base = { count, positions, normals: null, alpha: null };
  }
  if (!base) return null;
  if (spec.deform.length === 0 && spec.distribution.length === 0) return base;
  const positions = new Float32Array(base.positions);
  const radius = resolveDistributionRadius(spec, supply);
  for (let i = 0; i < count; i++) {
    let x = positions[i * 3];
    let y = positions[i * 3 + 1];
    let z = positions[i * 3 + 2];
    if (spec.deform.length > 0) {
      [x, y, z] = applyDeformOps(spec.deform, x, y, z);
    }
    if (spec.distribution.length > 0) {
      [x, y, z] = applyDistributionOps(spec.distribution, x, y, z, radius);
    }
    positions[i * 3] = x;
    positions[i * 3 + 1] = y;
    positions[i * 3 + 2] = z;
  }
  return { count, positions, normals: base.normals, alpha: base.alpha };
}

/** Parse + resolve in one call. */
export function resolveShapeStack(
  raw: string | null | undefined,
  supply: ShapeStackSupply,
): ShapeStackPoints | null {
  const spec = parseShapeStack(raw);
  if (!spec) return null;
  return resolveShapeStackPoints(spec, supply);
}

/**
 * Pack a resolved point set into the morph-layout RGBA
 * cloud (count * 4, xyz + alpha) that
 * lib/gpgpuInitialData.ts consumes as its `cloud` emission
 * source; points without an alpha lane ride alpha 1, the
 * bake's own default.
 */
export function shapeStackToCloudRgba(points: ShapeStackPoints): Float32Array {
  const out = new Float32Array(points.count * 4);
  for (let i = 0; i < points.count; i++) {
    out[i * 4] = points.positions[i * 3];
    out[i * 4 + 1] = points.positions[i * 3 + 1];
    out[i * 4 + 2] = points.positions[i * 3 + 2];
    out[i * 4 + 3] = points.alpha ? points.alpha[i] : 1;
  }
  return out;
}

// ---------------------------------------------------------------------------
// Placement connection (Layer 1 WP8, phase C) — appended.
//
// The placement grammar (lib/gpgpuPlacement.ts) generates
// point sets by rule (grid / ring / path / surface) where the
// sources above generate them by shape. This section is the
// one connection point between the two: a placement stack
// names a placement operator plus the same two columns a
// shape stack names, and resolves placement -> deform ->
// distribution in the same fixed order, through the same
// parsers and appliers, into the same ShapeStackPoints shape
// (normals / alpha null — placement supplies neither). The
// sections above are untouched: no existing parse or resolve
// path changes, and a placement stack with both columns
// empty is the placement operator's own output, bit for bit.
// ---------------------------------------------------------------------------

import {
  parsePlacementSpec,
  resolvePlacementPoints,
  type PlacementSpec,
} from './gpgpuPlacement';

/** The placement sibling of ShapeStackSpec. */
export interface PlacementStackSpec {
  placement: PlacementSpec;
  /** Deform column (WP8 phase A grammar), resolved. */
  deform: DeformOp[];
  /** Distribution column (stage 2 B5 grammar), resolved. */
  distribution: DistOp[];
  /** Distribution radius override; 0 = auto (the supply
   *  radius, then 1 — a placement names no radius of its
   *  own for the column). */
  distributionRadius: number;
}

/**
 * Parse a placement stack description: {placement, deform,
 * distribution, distributionRadius}. The placement accepts
 * either authored form (the object itself or its JSON
 * string) and goes through parsePlacementSpec verbatim, so
 * its sanitisation is the placement grammar's own; the
 * columns reuse this module's parsers exactly as
 * parseShapeStack does. Returns null when the placement
 * names nothing generatable.
 */
export function parsePlacementStack(raw: string | null | undefined): PlacementStackSpec | null {
  if (!raw) return null;
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!parsed || typeof parsed !== 'object') return null;
  const root = parsed as Record<string, unknown>;
  const pRaw = root.placement;
  const placement =
    typeof pRaw === 'string'
      ? parsePlacementSpec(pRaw)
      : pRaw && typeof pRaw === 'object'
        ? parsePlacementSpec(JSON.stringify(pRaw))
        : null;
  if (!placement) return null;
  return {
    placement,
    deform: parseColumn(root.deform, parseDeformOps) as DeformOp[],
    distribution: parseColumn(root.distribution, parseDistributionOps) as DistOp[],
    distributionRadius: positiveOr(root.distributionRadius, 0),
  };
}

/**
 * Resolve a parsed placement stack: generate the placement
 * points, apply the deform column in list order, then the
 * distribution column in list order — the shape stack's
 * fixed order, over the placement grammar's point set.
 */
export function resolvePlacementStackPoints(
  spec: PlacementStackSpec,
  supply: ShapeStackSupply,
): ShapeStackPoints | null {
  const placed = resolvePlacementPoints(spec.placement, { count: supply.count, seed: supply.seed });
  if (!placed) return null;
  const { count } = placed;
  if (spec.deform.length === 0 && spec.distribution.length === 0) {
    return { count, positions: placed.positions, normals: null, alpha: null };
  }
  const positions = new Float32Array(placed.positions);
  const radius =
    supply.radius !== undefined && supply.radius > 0
      ? supply.radius
      : spec.distributionRadius > 0
        ? spec.distributionRadius
        : 1;
  for (let i = 0; i < count; i++) {
    let x = positions[i * 3];
    let y = positions[i * 3 + 1];
    let z = positions[i * 3 + 2];
    if (spec.deform.length > 0) {
      [x, y, z] = applyDeformOps(spec.deform, x, y, z);
    }
    if (spec.distribution.length > 0) {
      [x, y, z] = applyDistributionOps(spec.distribution, x, y, z, radius);
    }
    positions[i * 3] = x;
    positions[i * 3 + 1] = y;
    positions[i * 3 + 2] = z;
  }
  return { count, positions, normals: null, alpha: null };
}

/** Parse + resolve a placement stack in one call. */
export function resolvePlacementStack(
  raw: string | null | undefined,
  supply: ShapeStackSupply,
): ShapeStackPoints | null {
  const spec = parsePlacementStack(raw);
  if (!spec) return null;
  return resolvePlacementStackPoints(spec, supply);
}

// ---------------------------------------------------------------------------
// Shape blend connection (Layer 1 WP8, phase E) — appended.
//
// Two shape stacks and a blend parameter: {a, b, t}. Each
// side is a full stack description (source + columns) parsed
// by parseShapeStack verbatim, resolved by
// resolveShapeStackPoints under the one supply, and the two
// point sets are then blended by lib/gpgpuShapeBlend.ts —
// vertex-correspondence interpolation (point i against
