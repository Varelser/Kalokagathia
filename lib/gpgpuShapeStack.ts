import {
  blendShapePointSets,
  clampBlendT,
  type ShapeBlendPointSet,
} from './gpgpuShapeBlend';

/** A blend of two stacks: the resolved sides plus t. */
export interface ShapeBlendSpec {
  a: ShapeStackSpec;
  b: ShapeStackSpec;
  /** Blend parameter, clamped to [0, 1] at parse time. */
  t: number;
}

function parseStackSide(raw: unknown): ShapeStackSpec | null {
  if (typeof raw === 'string') return parseShapeStack(raw);
  if (raw && typeof raw === 'object') return parseShapeStack(JSON.stringify(raw));
  return null;
}

/**
 * Parse a blend description: {a, b, t}. Each side accepts
 * either authored form (the stack object itself or its JSON
 * string) and goes through parseShapeStack verbatim, so its
 * sanitisation is the stack grammar's own. Returns null
 * when either side names nothing generatable; a missing or
 * unusable t resolves to 0 (the A side verbatim).
 */
export function parseShapeBlend(raw: string | null | undefined): ShapeBlendSpec | null {
  if (!raw) return null;
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!parsed || typeof parsed !== 'object') return null;
  const root = parsed as Record<string, unknown>;
  const a = parseStackSide(root.a);
  const b = parseStackSide(root.b);
  if (!a || !b) return null;
  return { a, b, t: clampBlendT(finiteOr(root.t, NaN)) };
}

/**
 * Resolve a parsed blend: resolve both stacks under the
 * supply and blend the point sets. Returns null when
 * either side cannot resolve under this supply.
 */
export function resolveShapeBlendPoints(
  spec: ShapeBlendSpec,
  supply: ShapeStackSupply,
): ShapeStackPoints | null {
  const pa = resolveShapeStackPoints(spec.a, supply);
  if (!pa) return null;
  const pb = resolveShapeStackPoints(spec.b, supply);
  if (!pb) return null;
  const blended: ShapeBlendPointSet = blendShapePointSets(pa, pb, spec.t);
  return {
    count: blended.count,
    positions: blended.positions,
    normals: blended.normals,
    alpha: blended.alpha,
  };
}

/** Parse + resolve a shape blend in one call. */
export function resolveShapeBlend(
  raw: string | null | undefined,
  supply: ShapeStackSupply,
): ShapeStackPoints | null {
  const spec = parseShapeBlend(raw);
  if (!spec) return null;
  return resolveShapeBlendPoints(spec, supply);
}
