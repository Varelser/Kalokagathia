export function searchParameters(query: string, limit = 30): ParameterCatalogEntry[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return [];
  return PARAMETER_CATALOG.filter(
    (entry) =>
      entry.label.toLowerCase().includes(needle) ||
      entry.key.toLowerCase().includes(needle) ||
      (entry.description ?? '').includes(query.trim()),
  ).slice(0, limit);
}
