// Non-blocking GPU-tier warnings (2026-11-11): when a visitor enables a
// feature whose recommended tier is above their GPU's tier, show a
// dismissible Japanese notice. Warnings inform, never block. Dismissal
// with 「今後表示しない」 is remembered per feature for the session
// (sessionStorage); a plain close hides only that instance.
//
// The banner UI lives in components/GpuTierWarningHost.tsx and renders
// whatever this store holds.

import {
  GPU_TIER_LABELS_JA,
  GPU_TIER_ORDER,
  resolveEffectiveTierSync,
  type GpuTier,
} from './gpuTier';

export interface GpuTierWarning {
  id: number;
  featureId: string;
  message: string;
}

const DISMISSED_STORAGE_KEY = 'kalokagathia.gpuTierWarnings.dismissed.v1';

/** iMac-measured fps below this marks a catalog preset as 'heavy'. */
export const HEAVY_PRESET_FPS_THRESHOLD = 15;

let warnings: GpuTierWarning[] = [];
let nextWarningId = 1;
const listeners = new Set<() => void>();

function notify(): void {
  listeners.forEach((listener) => listener());
}

export function subscribeGpuTierWarnings(listener: () => void): () => void {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}

export function getGpuTierWarnings(): GpuTierWarning[] {
  return warnings;
}

// In-memory mirror of the dismissed set: the source of truth within the
// session, persisted to sessionStorage when available (storage can be
// blocked or absent, e.g. in tests — dismissal must still hold).
const memoryDismissed = new Set<string>();

function readDismissed(): Set<string> {
  const dismissed = new Set<string>(memoryDismissed);
  try {
    if (typeof sessionStorage === 'undefined') return dismissed;
    const raw = sessionStorage.getItem(DISMISSED_STORAGE_KEY);
    if (!raw) return dismissed;
    const parsed = JSON.parse(raw) as unknown;
    if (Array.isArray(parsed)) {
      parsed.filter((v): v is string => typeof v === 'string').forEach((v) => dismissed.add(v));
    }
    return dismissed;
  } catch {
    return dismissed;
  }
}

function writeDismissed(featureId: string): void {
  memoryDismissed.add(featureId);
  try {
    if (typeof sessionStorage === 'undefined') return;
    sessionStorage.setItem(DISMISSED_STORAGE_KEY, JSON.stringify([...readDismissed()]));
  } catch { /* ignore */ }
}

export function isFeatureWarningDismissed(featureId: string): boolean {
  return readDismissed().has(featureId);
}

/** Queue a warning unless the feature was session-dismissed or is already shown. */
export function pushGpuTierWarning(featureId: string, message: string): boolean {
  if (isFeatureWarningDismissed(featureId)) return false;
  if (warnings.some((warning) => warning.featureId === featureId)) return false;
  warnings = [...warnings, { id: nextWarningId, featureId, message }];
  nextWarningId += 1;
  notify();
  return true;
}

export function dismissGpuTierWarning(id: number, dontShowAgain: boolean): void {
  const target = warnings.find((warning) => warning.id === id);
  if (!target) return;
  if (dontShowAgain) writeDismissed(target.featureId);
  warnings = warnings.filter((warning) => warning.id !== id);
  notify();
}

/** Warning (a): a feature with a recommended tier was just enabled. */
export function warnFeatureAboveTier(
  featureId: string,
  featureLabel: string,
  recommendedTier: GpuTier,
): boolean {
  const tier = resolveEffectiveTierSync();
  if (GPU_TIER_ORDER[tier] >= GPU_TIER_ORDER[recommendedTier]) return false;
  return pushGpuTierWarning(
    featureId,
    `この機能は ${GPU_TIER_LABELS_JA[recommendedTier]} 以上のGPU推奨です（${featureLabel}／現在のGPUティア: ${GPU_TIER_LABELS_JA[tier]}）。そのまま使うこともできますが、動作が重くなる場合があります。`,
  );
}

// ---------------------------------------------------------------------------
// Warning (b): heavy catalog presets on 'entry' GPUs. The fps index is
// generated by preset-analysis/build_catalog.py into /catalog/fps.json
// from the same screening results the catalog pages display.
// ---------------------------------------------------------------------------

interface CatalogFpsIndex {
  byId: Record<string, number>;
  byName: Record<string, number>;
}

let catalogFpsPromise: Promise<CatalogFpsIndex | null> | null = null;

export function loadCatalogFpsIndex(): Promise<CatalogFpsIndex | null> {
  if (!catalogFpsPromise) {
    catalogFpsPromise = (async () => {
      try {
        if (typeof fetch === 'undefined') return null;
        const response = await fetch('/catalog/fps.json', { credentials: 'same-origin' });
        if (!response.ok) return null;
        const parsed = (await response.json()) as Partial<CatalogFpsIndex>;
        return {
          byId: parsed.byId ?? {},
          byName: parsed.byName ?? {},
        };
      } catch {
        return null;
      }
    })();
  }
  return catalogFpsPromise;
}

export function lookupCatalogFps(
  index: CatalogFpsIndex,
  preset: { id: string; name: string },
): number | null {
  const byId = index.byId[preset.id];
  if (typeof byId === 'number') return byId;
  const byName = index.byName[preset.name];
  return typeof byName === 'number' ? byName : null;
}

/**
 * Fire warning (b) when an 'entry'-tier visitor applies a catalog preset
 * measured below HEAVY_PRESET_FPS_THRESHOLD fps on the reference iMac.
 * Fire-and-forget: applying the preset is never delayed or blocked.
 */
export function maybeWarnHeavyPreset(preset: { id: string; name: string }): void {
  if (resolveEffectiveTierSync() !== 'entry') return;
  if (isFeatureWarningDismissed('heavy-preset')) return;
  void loadCatalogFpsIndex().then((index) => {
    if (!index) return;
    const fps = lookupCatalogFps(index, preset);
    if (fps === null || fps >= HEAVY_PRESET_FPS_THRESHOLD) return;
    pushGpuTierWarning(
      'heavy-preset',
      `このプリセット（${preset.name}）は測定環境で ${Math.round(fps * 10) / 10}fps の重量級です。この機能は ${GPU_TIER_LABELS_JA.standard} 以上のGPU推奨です（現在のGPUティア: ${GPU_TIER_LABELS_JA.entry}）。そのまま使うこともできますが、動作が重くなる場合があります。Lite 版のプリセットを使うと軽くなります。`,
    );
  });
}
