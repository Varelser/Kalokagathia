export function getParameterDescription(key: string): string | undefined {
  const direct = DESCRIPTIONS[key];
  if (direct) return direct;
  if (key.startsWith('layer3')) {
    const mirrored = DESCRIPTIONS[key.replace(/^layer3/, 'layer2')];
    if (mirrored) return mirrored.replaceAll('Layer 2', 'Layer 3');
  }
  return undefined;
}
