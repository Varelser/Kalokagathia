/** One step of a layer's motion graph (free-wiring stage 3). */
export type MotionGraphInput = 'prev' | 'source' | 'branch';

export interface MotionGraphStep {
  motion: Layer2Type;
  input: MotionGraphInput;
  /** 0..1 mix weight of the step's motion result into the main register. */
  blend: number;
  /** Copy the main register into the branch register before this step runs. */
  saveBranch: boolean;
}

export type MotionDagNodeKind = 'motion' | 'mix' | 'scale' | 'source' | 'copy';

/**
 * One node of a layer motion DAG (free-wiring stage 4). Registers are
 * addressed by id: 0 = main (the position entering the DAG section),
 * 1 = source (the position that entered the layer's own stack), and
 * node i (0-based) writes register i + 2. Inputs may only reference
 * strictly earlier registers, so cycles are structurally impossible.
 */
export interface MotionDagNode {
  kind: MotionDagNodeKind;
  /** Motion applied by 'motion' nodes; ignored by other kinds. */
  motion?: Layer2Type;
  /** Register id read as the primary input. */
  inA: number;
  /** Register id read as the secondary input ('mix' nodes only). */
  inB: number;
  /** blend 0..1 for 'mix', scale factor for 'scale'; ignored otherwise. */
  param: number;
}

